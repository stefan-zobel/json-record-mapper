package dev.json.records;

import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.runner.Runner;
import org.openjdk.jmh.runner.RunnerException;
import org.openjdk.jmh.runner.options.OptionsBuilder;

import java21.util.json.Json;
import java21.util.json.JsonArray;
import java21.util.json.JsonNumber;
import java21.util.json.JsonObject;
import java21.util.json.JsonString;
import java21.util.json.JsonValue;

import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.TimeUnit;

// JMH benchmark, part of the test sources (it is not run by the unit tests). To run it:
// - with Maven: mvn -Pbench test-compile exec:exec
//   (JMH options, e.g.: -Djmh.args="RecordMapperBench -f 1 -wi 1 -i 1 -prof gc")
// - from the IDE: run main() as a Java application; the benchmark code generated by the JMH
//   annotation processor must exist, i.e. run mvn test-compile first or enable annotation
//   processing in the IDE (m2e-apt in Eclipse)
//
// It maps a typical REST response (an order with 10 line items) with the RecordMapper and,
// for comparison, with handwritten code using the java21.util.json API, both
// - on a document parsed once in the setup (*Map). The JSON values of java21.util.json cache
//   the strings and numbers they have converted once, so this measures the cached path, and
// - including the parsing of the JSON text on every call (*ParseAndMap), end to end.
// parseOnly measures the parsing alone. *ToJson writes the order as a JsonObject (without
// generating the JSON text).
//
// Results (JDK 21.0.3, -prof gc; error margins of 12-18 %):
// Benchmark                                                     Mode  Cnt      Score      Error   Units
// RecordMapperBench.handwrittenMap                              avgt   10    730,519 ±   90,693   ns/op
// RecordMapperBench.handwrittenMap:gc.alloc.rate.norm           avgt   10   1304,005 ±    0,001    B/op
// RecordMapperBench.handwrittenParseAndMap                      avgt   10   7136,703 ± 1268,046   ns/op
// RecordMapperBench.handwrittenParseAndMap:gc.alloc.rate.norm   avgt   10  17808,049 ±    0,009    B/op
// RecordMapperBench.parseOnly                                   avgt   10   4342,407 ±  530,551   ns/op
// RecordMapperBench.parseOnly:gc.alloc.rate.norm                avgt   10  12072,030 ±    0,004    B/op
// RecordMapperBench.recordMapperMap                             avgt   10   1455,214 ±  236,095   ns/op
// RecordMapperBench.recordMapperMap:gc.alloc.rate.norm          avgt   10   1328,010 ±    0,002    B/op
// RecordMapperBench.recordMapperParseAndMap                     avgt   10   7123,985 ±  810,196   ns/op
// RecordMapperBench.recordMapperParseAndMap:gc.alloc.rate.norm  avgt   10  17832,049 ±    0,006    B/op
// End to end, the RecordMapper is as fast as the handwritten code (parsing takes about 60 %);
// on the cached path it takes about twice as long, with almost the same allocation.
//
// Writing JSON (JDK 21.0.3, -prof gc):
// RecordMapperBench.handwrittenToJson                      avgt   10   3014,645 ± 244,251   ns/op
// RecordMapperBench.handwrittenToJson:gc.alloc.rate.norm   avgt   10  15464,021 ±   0,002    B/op
// RecordMapperBench.recordMapperToJson                     avgt   10   3913,762 ± 241,702   ns/op
// RecordMapperBench.recordMapperToJson:gc.alloc.rate.norm  avgt   10  15176,027 ± 191,237    B/op
// The RecordMapper takes about 30 % longer than the handwritten code, with the same allocation.
@Warmup(iterations = 5, time = 1, timeUnit = TimeUnit.SECONDS)
@Measurement(iterations = 5, time = 1, timeUnit = TimeUnit.SECONDS)
@Fork(2)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@State(Scope.Benchmark)
public class RecordMapperBench {
    public enum Status { OPEN, SHIPPED, CANCELLED }

    public record Address(String street, String city, String zip) {}

    public record LineItem(String sku, String description, int quantity, BigDecimal unitPrice) {}

    public record Order(long id, String customer, Status status, Optional<String> note,
                        Address shippingAddress, List<LineItem> items, BigDecimal total) {}

    private static final RecordMapper RECORD_MAPPER = RecordMapper.of(MethodHandles.lookup());

    // The decoder of the RecordMapper for Order, the method handle that the proxy returned by
    // MethodHandleProxies calls: as a constant, the JIT can inline the whole handle tree, in
    // a field it cannot (decoderHandle*). It is taken from the implementation by reflection.
    private static final MethodHandle DECODER_CONSTANT = decoderHandle(Order.class);

    private static final String JSON = orderJson(10);

    private JsonObject parsed;

    private Order order;

    private MethodHandle decoderField;

    public static void main(String[] args) throws RunnerException {
        new Runner(new OptionsBuilder().include(RecordMapperBench.class.getSimpleName()).build()).run();
    }

    private static String orderJson(int itemCount) {
        var json = new StringBuilder("""
                {
                  "id": 1234567890123,
                  "customer": "Alice Example",
                  "status": "SHIPPED",
                  "note": "Please leave the parcel at the back door.",
                  "shippingAddress": { "street": "123 Main St", "city": "Anytown", "zip": "12345" },
                  "items": [
                """);
        for (int i = 1; i <= itemCount; i++) {
            json.append("""
                        { "sku": "SKU-%04d", "description": "Item number %d", "quantity": %d, "unitPrice": %d.%02d }%s
                    """.formatted(i, i, i, 10 + i, i * 7 % 100, i < itemCount ? "," : ""));
        }
        return json.append("""
                  ],
                  "total": 1234.50
                }
                """).toString();
    }

    @Setup
    public void setup() {
        parsed = (JsonObject) Json.parse(JSON);
        // both variants must do the same work and produce the same result
        var expected = handwritten(parsed);
        var actual = RECORD_MAPPER.fromTyped(parsed, Order.class);
        if (!expected.equals(actual) || expected.items().size() != 10) {
            throw new IllegalStateException("different results: " + expected + " / " + actual);
        }
        order = expected;
        decoderField = DECODER_CONSTANT;
        if (!expected.equals(decoderHandleField()) || !expected.equals(decoderHandleConstant())) {
            throw new IllegalStateException("different results of the decoder handle");
        }
        var expectedJson = handwrittenToJson(order).toString();
        var actualJson = RECORD_MAPPER.toJson(order).toString();
        if (!expectedJson.equals(actualJson)) {
            throw new IllegalStateException("different results: " + expectedJson + " / " + actualJson);
        }
    }

    // DecoderFactory.topLevelDecoder of the RecordMapper, a method handle of type (JsonValue)Object
    private static MethodHandle decoderHandle(Class<?> type) {
        try {
            var lookup = MethodHandles.privateLookupIn(RecordMapperImpl.class, MethodHandles.lookup());
            var factoryClass = lookup.findClass(RecordMapperImpl.class.getName() + "$DecoderFactory");
            var factory = (Object) lookup.findGetter(RecordMapperImpl.class, "factory", factoryClass)
                    .invoke(RECORD_MAPPER);
            var topLevelDecoder = lookup.findVirtual(factoryClass, "topLevelDecoder",
                    MethodType.methodType(MethodHandle.class, Class.class));
            return (MethodHandle) topLevelDecoder.invoke(factory, type);
        } catch (Throwable e) {
            throw new IllegalStateException(e);
        }
    }

    // writing JSON by hand with the java21.util.json API
    static JsonObject handwrittenToJson(Order order) {
        var items = new ArrayList<JsonValue>(order.items().size());
        for (var item : order.items()) {
            var members = new LinkedHashMap<String, JsonValue>();
            members.put("sku", JsonString.of(item.sku()));
            members.put("description", JsonString.of(item.description()));
            members.put("quantity", JsonNumber.of(item.quantity()));
            members.put("unitPrice", JsonNumber.of(item.unitPrice().toString()));
            items.add(JsonObject.of(members));
        }
        var address = new LinkedHashMap<String, JsonValue>();
        address.put("street", JsonString.of(order.shippingAddress().street()));
        address.put("city", JsonString.of(order.shippingAddress().city()));
        address.put("zip", JsonString.of(order.shippingAddress().zip()));
        var members = new LinkedHashMap<String, JsonValue>();
        members.put("id", JsonNumber.of(order.id()));
        members.put("customer", JsonString.of(order.customer()));
        members.put("status", JsonString.of(order.status().name()));
        order.note().ifPresent(note -> members.put("note", JsonString.of(note)));
        members.put("shippingAddress", JsonObject.of(address));
        members.put("items", JsonArray.of(items));
        members.put("total", JsonNumber.of(order.total().toString()));
        return JsonObject.of(members);
    }

    // the mapping written by hand with the java21.util.json API
    static Order handwritten(JsonValue json) {
        var itemValues = json.get("items").asList();
        var items = new LineItem[itemValues.size()];
        for (int i = 0; i < items.length; i++) {
            var item = itemValues.get(i);
            items[i] = new LineItem(
                    item.get("sku").asString(),
                    item.get("description").asString(),
                    item.get("quantity").asInt(),
                    new BigDecimal(item.get("unitPrice").toString()));
        }
        var address = json.get("shippingAddress");
        return new Order(
                json.get("id").asLong(),
                json.get("customer").asString(),
                Status.valueOf(json.get("status").asString()),
                json.tryGet("note").flatMap(JsonValue::tryValue).map(JsonValue::asString),
                new Address(address.get("street").asString(), address.get("city").asString(),
                        address.get("zip").asString()),
                Collections.unmodifiableList(Arrays.asList(items)),
                new BigDecimal(json.get("total").toString()));
    }

    @Benchmark
    public Order handwrittenMap() {
        return handwritten(parsed);
    }

    @Benchmark
    public Order recordMapperMap() {
        return RECORD_MAPPER.fromTyped(parsed, Order.class);
    }

    @Benchmark
    public Order decoderHandleField() {
        try {
            return (Order) (Object) decoderField.invokeExact((JsonValue) parsed);
        } catch (Throwable e) {
            throw new IllegalStateException(e);
        }
    }

    @Benchmark
    public Order decoderHandleConstant() {
        try {
            return (Order) (Object) DECODER_CONSTANT.invokeExact((JsonValue) parsed);
        } catch (Throwable e) {
            throw new IllegalStateException(e);
        }
    }

    @Benchmark
    public Order handwrittenParseAndMap() {
        return handwritten(Json.parse(JSON));
    }

    @Benchmark
    public Order recordMapperParseAndMap() {
        return RECORD_MAPPER.fromTyped((JsonObject) Json.parse(JSON), Order.class);
    }

    @Benchmark
    public JsonValue parseOnly() {
        return Json.parse(JSON);
    }

    @Benchmark
    public JsonObject handwrittenToJson() {
        return handwrittenToJson(order);
    }

    @Benchmark
    public JsonObject recordMapperToJson() {
        return RECORD_MAPPER.toJson(order);
    }
}
